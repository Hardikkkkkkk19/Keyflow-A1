export function getRandomTimeText(includePunctuation = false, includeNumbers = false): string {
  const selected = TIME_TEXTS[Math.floor(Math.random() * TIME_TEXTS.length)];
  let result = selected;
  if (includeNumbers) {
    result +=
      " In 2024, top developers average over 85 WPM with 98% accuracy across 100% of sessions.";
  }
  if (!includePunctuation) {
    // Keep sentence readable
    return result;
  }
  return result;
}

export function getRandomWords(
  count: number,
  includePunctuation = false,
  includeNumbers = false,
): string {
  const combinedPool = [...WORD_LISTS.easy, ...WORD_LISTS.medium];
  const chosenWords: string[] = [];

  for (let i = 0; i < count; i++) {
    let word = combinedPool[Math.floor(Math.random() * combinedPool.length)];
    if (includePunctuation && Math.random() > 0.8) {
      const puncts = [",", ".", ";", "!", "?"];
      word += puncts[Math.floor(Math.random() * puncts.length)];
    }
    if (includeNumbers && Math.random() > 0.9) {
      word = String(Math.floor(Math.random() * 900) + 10);
    }
    chosenWords.push(word);
  }

  return chosenWords.join(" ");
}

export function getRandomQuote(option: "short" | "medium" | "long"): string {
  const list = QUOTES[option] || QUOTES.medium;
  return list[Math.floor(Math.random() * list.length)];
}

