export function getRandomCodeSnippet(
  lang: string,
  difficulty: CodeDifficulty = "Intermediate",
): string {
  const validLangs = ["javascript", "python", "java", "html", "css", "sql"];
  const normalizedLang = validLangs.includes(lang.toLowerCase())
    ? (lang.toLowerCase() as any)
    : "javascript";
  return getRandomCodeSnippetFromUtils(normalizedLang, difficulty);
}

